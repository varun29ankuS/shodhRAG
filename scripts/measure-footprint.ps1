    New-Item -ItemType Directory -Force -Path $Folder | Out-Null
    $topics = @(
        @{ name = 'tide-pools'; title = 'Field Notes on Tide Pool Ecology'; subject = 'tide pools'; detail = 'Sea stars, anemones and barnacles share each rock shelf, and the pools are mapped at every low tide.' },
        @{ name = 'bridge-loads'; title = 'A Short Study of Footbridge Loads'; subject = 'footbridges'; detail = 'Deck sway is measured under walking crowds, and the damping of each span is compared with its design value.' },
        @{ name = 'sourdough'; title = 'Fermentation Timing in Sourdough Starters'; subject = 'sourdough starters'; detail = 'Rise height is logged every hour at three kitchen temperatures, with the flour and water ratio held fixed.' }
    )
    foreach ($topic in $topics) {
        $lines = New-Object System.Collections.ArrayList
        [void]$lines.Add($topic.title)
        [void]$lines.Add('')
        for ($section = 1; $section -le 4; $section++) {
