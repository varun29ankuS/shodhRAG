            [void]$lines.Add("The method in section $section is repeated three times and the results agree.")
            [void]$lines.Add('')
        }
        New-FixturePdf -Path (Join-Path $Folder "$($topic.name).pdf") -Lines $lines
    }
}

# --- Launch and measure ----------------------------------------------------------

function Start-Shodh([string]$ProfileDir) {
    # The app inherits this process's environment: set the measured
    # environment here for the launch and put everything back after.
    $saved = @{}
    foreach ($item in @(Get-ChildItem Env:)) {
        if ($item.Name -match $StrippedEnv) {
            $saved[$item.Name] = $item.Value
            Remove-Item -LiteralPath "Env:$($item.Name)"
        }
    }
    $logDir = Split-Path -Parent $ProfileDir
    try {
        $env:SHODH_DATA_DIR = $ProfileDir
        $env:WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS = $WebViewArgs
        if ($ModelPath) { $env:MODEL_PATH = $ModelPath }
        $launchMs = Get-EpochMs
        $process = Start-Process -FilePath $ExePath -WorkingDirectory ([IO.Path]::GetDirectoryName($ExePath)) -PassThru `
            -RedirectStandardOutput (Join-Path $logDir ("app-{0}.log" -f $launchMs)) -RedirectStandardError (Join-Path $logDir ("app-{0}.err.log" -f $launchMs))
    } finally {
        foreach ($name in 'SHODH_DATA_DIR', 'WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS', 'MODEL_PATH') {
            Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
        }
        foreach ($name in $saved.Keys) { Set-Item -LiteralPath "Env:$name" -Value $saved[$name] }
    }
    [pscustomobject]@{ Process = $process; LaunchMs = $launchMs; Start = $process.StartTime; LogDir = $logDir }
}

function Stop-Shodh($App) {
    $rootId = $App.Process.Id
    $tree = @(Get-ProcessTree $rootId $App.Start)
    & taskkill.exe /PID $rootId /T /F 2>&1 | Out-Null
    $deadline = (Get-Date).AddSeconds(20)
    foreach ($p in $tree) {
        while ((Get-Date) -lt $deadline -and (Get-Process -Id ([int]$p.ProcessId) -ErrorAction SilentlyContinue)) {
            Start-Sleep -Milliseconds 200
        }
        $left = Get-Process -Id ([int]$p.ProcessId) -ErrorAction SilentlyContinue
        if ($left -and $left.StartTime -ge $App.Start.AddSeconds(-1)) { Stop-Process -Id $left.Id -Force -ErrorAction SilentlyContinue }
    }
}

# Wait for the shell-mounted mark. Returns the marks (ms after launch) and the
# DevTools connection, sampling memory every second meanwhile.
function Wait-Window($App, [System.Collections.ArrayList]$Samples) {
    $deadline = (Get-Date).AddSeconds($StartupTimeoutSeconds)
    $cdp = $null
    while ((Get-Date) -lt $deadline) {
        if ($App.Process.HasExited) { throw "Shodh exited during startup (code $($App.Process.ExitCode))" }
        [void]$Samples.Add((Get-Sample $App.Process.Id $App.Start $App.LaunchMs))
        if ($null -eq $cdp) {
            $url = Get-PageSocketUrl
            if ($url) { $cdp = Connect-Cdp $url }
        }
        if ($null -ne $cdp) {
            $marks = (Invoke-PageScript $cdp $MarksScript) | ConvertFrom-Json
            if ($null -ne $marks.shellMounted) {
                $relative = [ordered]@{}
                foreach ($name in 'shellMounted', 'indexReady', 'conversationsLoaded') {
                    $value = $marks.$name
                    $relative[$name] = if ($null -eq $value) { $null } else { [math]::Round(([double]$value - $App.LaunchMs) / 1000.0, 3) }
                }
                return [pscustomobject]@{ Cdp = $cdp; Marks = $relative }
            }
        }
        Start-Sleep -Milliseconds 250
    }
    Close-Cdp $cdp
    throw "No usable window within $StartupTimeoutSeconds s"
}

function Invoke-Idle($App, [System.Collections.ArrayList]$Samples, [string]$Phase) {
    $start = Get-Date
    $idle = New-Object System.Collections.ArrayList
    while (((Get-Date) - $start).TotalSeconds -lt $IdleSeconds) {
        Start-Sleep -Seconds $IntervalSeconds
        if ($App.Process.HasExited) { throw "Shodh exited while idle (code $($App.Process.ExitCode))" }
        $sample = Get-Sample $App.Process.Id $App.Start $App.LaunchMs
        $sample | Add-Member -NotePropertyName phase -NotePropertyValue $Phase
        $sample | Add-Member -NotePropertyName idleSeconds -NotePropertyValue ([math]::Round(((Get-Date) - $start).TotalSeconds, 1))
        [void]$Samples.Add($sample)
        [void]$idle.Add($sample)
    }
    # Steady state: the second half of the idle period.
    $steady = @($idle | Where-Object { $_.idleSeconds -ge $IdleSeconds / 2 })
    if ($steady.Count -eq 0) { $steady = @($idle) }
    $groups = [ordered]@{}
    foreach ($g in 'core', 'webview2', 'agent-runtime', 'other') {
        $groups[$g] = [math]::Round((Get-Median @($steady | ForEach-Object { [double]$_.groupsMB[$g] })), 1)
    }
    [pscustomobject][ordered]@{
        totalMB  = [math]::Round((Get-Median @($steady | ForEach-Object { [double]$_.totalMB })), 1)
        groupsMB = $groups
    }
}

function Get-Peak([System.Collections.ArrayList]$Samples) {
    $groups = [ordered]@{}
    foreach ($g in 'core', 'webview2', 'agent-runtime', 'other') {
        $groups[$g] = [math]::Round(($Samples | ForEach-Object { [double]$_.groupsMB[$g] } | Measure-Object -Maximum).Maximum, 1)
    }
    [pscustomobject][ordered]@{
        totalMB  = [math]::Round(($Samples | ForEach-Object { [double]$_.totalMB } | Measure-Object -Maximum).Maximum, 1)
        groupsMB = $groups
    }
}

function Invoke-Ingest($App, $Cdp, [string]$Folder, [System.Collections.ArrayList]$Samples) {
    $invokeArgs = @{
        folderPath = $Folder
        spaceId    = 'footprint-fixtures'
        options    = @{ skip_indexed = $false; watch_changes = $false; process_subdirs = $false; priority = 'normal'; file_types = @() }
    } | ConvertTo-Json -Depth 5 -Compress
    $startScript = @"
(() => {
  window.__shodhFootprint = { done: false };
  window.__TAURI_INTERNALS__.invoke('link_folder_enhanced', $invokeArgs).then(
    r => { window.__shodhFootprint = { done: true, ok: true, result: r }; },
    e => { window.__shodhFootprint = { done: true, ok: false, error: String(e) }; });
  return true;
})()
"@
    [void](Invoke-PageScript $Cdp $startScript)
    $started = Get-Date
    while (((Get-Date) - $started).TotalSeconds -lt $IngestTimeoutSeconds) {
        Start-Sleep -Seconds 1
        $sample = Get-Sample $App.Process.Id $App.Start $App.LaunchMs
        $sample | Add-Member -NotePropertyName phase -NotePropertyValue 'ingest'
        [void]$Samples.Add($sample)
        $state = (Invoke-PageScript $Cdp 'JSON.stringify(window.__shodhFootprint)') | ConvertFrom-Json
        if ($state.done) {
            if (-not $state.ok) { throw "Indexing the fixtures failed: $($state.error)" }
            if ($state.result.files_processed -lt 3) {
                throw "Only $($state.result.files_processed) of 3 fixtures were indexed: $($state.result.failures | ConvertTo-Json -Compress)"
            }
            return [pscustomobject][ordered]@{
                seconds        = [math]::Round(((Get-Date) - $started).TotalSeconds, 1)
                filesProcessed = $state.result.files_processed
                chunks         = $state.result.total_chunks
            }
        }
    }
    throw "Indexing the fixtures did not finish within $IngestTimeoutSeconds s"
}

# Models the app loaded during the measured launch (lazy_model's log line).
function Get-ModelLoads($App) {
    $log = Get-ChildItem -LiteralPath $App.LogDir -Filter ("app-{0}*.log" -f $App.LaunchMs) -ErrorAction SilentlyContinue
    foreach ($file in $log) {
        foreach ($line in (Get-Content -LiteralPath $file.FullName -ErrorAction SilentlyContinue)) {
            $plain = $line -replace "$([char]27)\[[0-9;]*m", ''
            if ($plain -match 'Model loaded on first use' -and $plain -match 'model="?([\w-]+)"?') { $Matches[1] }
        }
    }
}

function Remove-Folder([string]$Path) {
    if ($KeepProfiles -or -not (Test-Path -LiteralPath $Path)) { return }
    for ($i = 0; $i -lt 10; $i++) {
        try {
            Remove-Item -LiteralPath $Path -Recurse -Force
            return
        } catch {
            Start-Sleep -Milliseconds 500
        }
    }
    Write-Warning "Could not remove $Path"
}

function Invoke-Run([string]$Kind, [int]$Index) {
    $work = Join-Path ([IO.Path]::GetTempPath()) ("shodh-footprint-" + [guid]::NewGuid().ToString('N'))
    $profileDir = Join-Path $work 'profile'
    New-Item -ItemType Directory -Force -Path $profileDir | Out-Null
    try {
        # Prime launch: creates the profile and the WebView2 user data.
        $prime = Start-Shodh $profileDir
        $primeSamples = New-Object System.Collections.ArrayList
        try {
            $primeWindow = Wait-Window $prime $primeSamples
            Close-Cdp $primeWindow.Cdp
        } finally {
            Stop-Shodh $prime
        }

        $app = Start-Shodh $profileDir
        $samples = New-Object System.Collections.ArrayList
        try {
            $window = Wait-Window $app $samples
            $ingest = $null
            try {
                if ($Kind -eq 'ingest') {
                    $fixtures = Join-Path $work 'fixtures'
                    New-Fixtures $fixtures
                    $ingest = Invoke-Ingest $app $window.Cdp $fixtures $samples
                }
                $idle = Invoke-Idle $app $samples 'idle'
            } finally {
                Close-Cdp $window.Cdp
            }
        } finally {
            Stop-Shodh $app
        }
        $modelLoads = @(Get-ModelLoads $app)
        Write-Host ("{0} run {1}: window {2:N2} s, idle {3:N1} MB (core {4:N1}, webview2 {5:N1}, agent-runtime {6:N1}, other {7:N1})" -f `
                $Kind, $Index, $window.Marks.shellMounted, $idle.totalMB, $idle.groupsMB['core'], $idle.groupsMB['webview2'], $idle.groupsMB['agent-runtime'], $idle.groupsMB['other'])
        [pscustomobject][ordered]@{
            scenario               = $Kind
            run                    = $Index
            coldWindowSeconds      = $primeWindow.Marks.shellMounted
            windowSeconds          = $window.Marks.shellMounted
            marksSeconds           = $window.Marks
            ingest                 = $ingest
            idle                   = $idle
            peak                   = Get-Peak $samples
            modelLoads             = $modelLoads
            samples                = $samples
        }
    } finally {
        Remove-Folder $work
    }
}

function Get-Summary([object[]]$RunResults) {
    $groups = [ordered]@{}
    foreach ($g in 'core', 'webview2', 'agent-runtime', 'other') {
        $groups[$g] = [ordered]@{
            idleMB = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.idle.groupsMB[$g] })), 1)
            peakMB = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.peak.groupsMB[$g] })), 1)
        }
    }
    [pscustomobject][ordered]@{
        runs                    = $RunResults.Count
        windowSecondsMedian     = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.windowSeconds })), 3)
        coldWindowSecondsMedian = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.coldWindowSeconds })), 3)
        idleTotalMBMedian       = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.idle.totalMB })), 1)
        peakTotalMBMedian       = [math]::Round((Get-Median @($RunResults | ForEach-Object { [double]$_.peak.totalMB })), 1)
        groups                  = $groups
    }
}

# Launch the app on a throwaway profile with MODEL_PATH = -ModelPath and run
# its own `install_search_models` (pinned URLs, SHA-256 checked).
function Install-SearchModels {
    $work = Join-Path ([IO.Path]::GetTempPath()) ("shodh-footprint-" + [guid]::NewGuid().ToString('N'))
    $profileDir = Join-Path $work 'profile'
    New-Item -ItemType Directory -Force -Path $profileDir | Out-Null
    try {
        $app = Start-Shodh $profileDir
        $samples = New-Object System.Collections.ArrayList
        try {
            $window = Wait-Window $app $samples
            try {
                Write-Host "Installing the search models into $ModelPath"
                $result = Invoke-PageScript $window.Cdp "window.__TAURI_INTERNALS__.invoke('install_search_models').then(r => JSON.stringify(r))" 3600
                Write-Host "Search models installed: $result"
            } finally {
                Close-Cdp $window.Cdp
            }
        } finally {
            Stop-Shodh $app
        }
    } finally {
        Remove-Folder $work
    }
}

# --- Main --------------------------------------------------------------------------

if ($InstallModels -and -not (Test-Models)) { Install-SearchModels }
$ModelsPresent = Test-Models
if ($Scenario -ne 'idle' -and -not $ModelsPresent) {
    throw "The ingest scenario needs the search models: pass -ModelPath with a multilingual-e5-base folder (or -InstallModels), or -Scenario idle."
}

$scenarios = if ($Scenario -eq 'all') { @('idle', 'ingest') } else { @($Scenario) }
$results = [ordered]@{}
foreach ($kind in $scenarios) {
    $runResults = New-Object System.Collections.ArrayList
    for ($i = 1; $i -le $Runs; $i++) {
        [void]$runResults.Add((Invoke-Run $kind $i))
    }
    $results[$kind] = [ordered]@{ summary = Get-Summary $runResults; runs = $runResults }
}

$os = Get-CimInstance -ClassName Win32_OperatingSystem -Property Caption, Version, TotalVisibleMemorySize
$cpu = Get-CimInstance -ClassName Win32_Processor -Property Name, NumberOfLogicalProcessors | Select-Object -First 1
$report = [ordered]@{
    measuredAt          = (Get-Date).ToUniversalTime().ToString('o')
    exe                 = $ExePath
    exeBytes            = (Get-Item -LiteralPath $ExePath).Length
    modelsPresent       = $ModelsPresent
    machine             = [ordered]@{
        os          = "$($os.Caption) $($os.Version)"
        memoryGB    = [math]::Round([double]$os.TotalVisibleMemorySize / 1MB, 1)
        cpu         = $cpu.Name
        logicalCpus = $cpu.NumberOfLogicalProcessors
    }
    definitions         = [ordered]@{
        memory = 'Private bytes (commit) of the launched process and all its descendants, in MB; idle = median of the samples in the second half of the idle period; peak = largest sample of the run; summaries are medians over runs.'
        window = 'Seconds from process launch to the shodh:shell-mounted performance mark (shell committed to the DOM), on a profile created by a prime launch; cold = the prime launch itself.'
    }
    settings            = [ordered]@{ runs = $Runs; idleSeconds = $IdleSeconds; intervalSeconds = $IntervalSeconds; webViewArgs = $WebViewArgs }
    scenarios           = $results
}
$json = $report | ConvertTo-Json -Depth 12
if ($Output) {
    [IO.File]::WriteAllText($Output, $json, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Report written to $Output"
} else {
    $json
}

$failures = New-Object System.Collections.ArrayList
if ($results.Contains('idle')) {
    $summary = $results['idle'].summary
    if ($BudgetIdleMB -gt 0 -and $summary.idleTotalMBMedian -gt $BudgetIdleMB) {
        [void]$failures.Add("idle memory $($summary.idleTotalMBMedian) MB is over the $BudgetIdleMB MB budget")
    }
    if ($BudgetWindowSeconds -gt 0 -and $summary.windowSecondsMedian -gt $BudgetWindowSeconds) {
        [void]$failures.Add("time to window $($summary.windowSecondsMedian) s is over the $BudgetWindowSeconds s budget")
    }
}
if ($failures.Count -gt 0) {
    foreach ($f in $failures) { Write-Host "BUDGET EXCEEDED: $f" }
    exit 1
}
