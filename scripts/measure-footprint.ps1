# A one-page PDF with the given lines in Helvetica (written by hand: no
# dependencies, nothing copyrighted).
function New-FixturePdf([string]$Path, [string[]]$Lines) {
    $escaped = $Lines | ForEach-Object { $_.Replace('\', '\\').Replace('(', '\(').Replace(')', '\)') }
    $content = New-Object System.Text.StringBuilder
    [void]$content.Append("BT /F1 11 Tf 14 TL 72 720 Td`n")
    foreach ($line in $escaped) { [void]$content.Append("($line) Tj T*`n") }
    [void]$content.Append("ET")
    $stream = $content.ToString()
    $objects = @(
        '<< /Type /Catalog /Pages 2 0 R >>',
        '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
        '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
        "<< /Length $([Text.Encoding]::ASCII.GetByteCount($stream)) >>`nstream`n$stream`nendstream"
    )
    $pdf = New-Object System.Text.StringBuilder
    [void]$pdf.Append("%PDF-1.4`n")
    $offsets = New-Object System.Collections.ArrayList
    for ($i = 0; $i -lt $objects.Count; $i++) {
        [void]$offsets.Add([Text.Encoding]::ASCII.GetByteCount($pdf.ToString()))
        [void]$pdf.Append("$($i + 1) 0 obj`n$($objects[$i])`nendobj`n")
    }
    $xref = [Text.Encoding]::ASCII.GetByteCount($pdf.ToString())
    [void]$pdf.Append("xref`n0 $($objects.Count + 1)`n0000000000 65535 f `n")
    foreach ($offset in $offsets) { [void]$pdf.Append(('{0:D10} 00000 n `n' -f $offset)) }
    [void]$pdf.Append("trailer`n<< /Size $($objects.Count + 1) /Root 1 0 R >>`nstartxref`n$xref`n%%EOF`n")
    [IO.File]::WriteAllBytes($Path, [Text.Encoding]::ASCII.GetBytes($pdf.ToString()))
}

