<#
.SYNOPSIS
    Measures Shodh's memory footprint and time to a usable window.

.DESCRIPTION
    Launches the given Shodh executable on a fresh, throwaway profile
    (SHODH_DATA_DIR in a temporary folder: never the user's own data) and
    samples the private memory of the app and every process it started
    (WebView2 browser, renderer, GPU and utility processes, the agent runtime,
    ...). Only the process tree rooted at the launched process is read; other
    Shodh instances on the machine are never enumerated, touched or stopped.

    Scenarios:
      idle    Start, wait for the window, idle -IdleSeconds.
      ingest  Start, wait for the window, index three small synthetic PDFs
              (generated by this script) through the same command the
              Library uses, then idle -IdleSeconds. No model is asked
              anything. Needs the search models (-ModelPath).

    Every scenario run gets a prime launch first (it creates the profile and
    the WebView2 user data; its time is reported as the cold start), then the
    measured launch on that profile. With -Runs N each scenario is measured N
    times and the summary is the median.

    Time to window: from launching the process to the frontend's
    `shodh:shell-mounted` performance mark (the sidebar, title bar and active
    view have committed to the DOM), read over the WebView2 DevTools protocol.
    The mark carries its own timestamp, so the polling interval does not
    affect the number.

    Memory: private bytes (commit charge, Win32_Process.PrivatePageCount) of
    each process, summed per group: core (the Shodh process), webview2,
    agent-runtime (omp), other. "Idle" is the median of the samples taken in
    the last half of the idle period; "peak" is the largest sample of the run.

.PARAMETER Exe
    The Shodh executable to measure (e.g. a release build).

.PARAMETER ModelPath
    Folder holding the search models (multilingual-e5-base/,
    ms-marco-MiniLM-L6-v2/), passed to the app as MODEL_PATH. Without it the
    app starts without search models and the ingest scenario cannot run.

.PARAMETER InstallModels
    When the search models are not in -ModelPath yet, have the app itself
    download and verify its pinned search models there first (Settings ->
    Search does the same). Used by CI to fill its model cache.

.PARAMETER WebViewArgsOverride
    WebView2 flags to measure with instead of the app's own (to compare
    flags; the DevTools port is added). Never used for the budget.

.PARAMETER BudgetIdleMB
    When above zero, exit with code 1 if the median idle total of the idle
    scenario exceeds it.

.PARAMETER BudgetWindowSeconds
    When above zero, exit with code 1 if the median time to window of the
    idle scenario exceeds it.

.EXAMPLE
    ./scripts/measure-footprint.ps1 -Exe C:\build\release\shodh-rag-app.exe -ModelPath D:\models -Output footprint.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Exe,

    [string]$ModelPath,

    [ValidateSet('idle', 'ingest', 'all')]
    [string]$Scenario = 'all',

    [ValidateRange(1, 20)]
    [int]$Runs = 3,

    [ValidateRange(10, 3600)]
    [int]$IdleSeconds = 60,

    [ValidateRange(1, 60)]
    [int]$IntervalSeconds = 5,

    [ValidateRange(5, 600)]
    [int]$StartupTimeoutSeconds = 90,

    [ValidateRange(5, 3600)]
    [int]$IngestTimeoutSeconds = 600,

    [ValidateRange(1024, 65535)]
    [int]$CdpPort = 9339,

    [string]$Output,

    [double]$BudgetIdleMB = 0,

    [double]$BudgetWindowSeconds = 0,

    [switch]$KeepProfiles,

    [switch]$InstallModels,

    [string]$WebViewArgsOverride
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$ExePath = (Resolve-Path -LiteralPath $Exe).Path
$ExeName = [System.IO.Path]::GetFileName($ExePath)
if ($InstallModels -and -not $ModelPath) {
    throw '-InstallModels needs -ModelPath (the folder to install the models into).'
}
if ($ModelPath) {
    if ($InstallModels) { New-Item -ItemType Directory -Force -Path $ModelPath | Out-Null }
    $ModelPath = (Resolve-Path -LiteralPath $ModelPath).Path
}
function Test-Models {
    if (-not $ModelPath) { return $false }
    $e5 = Join-Path $ModelPath 'multilingual-e5-base'
    [bool]((Test-Path -LiteralPath (Join-Path $e5 'tokenizer.json')) -and (Get-ChildItem -LiteralPath $e5 -Filter '*.onnx' -ErrorAction SilentlyContinue))
}

# WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS replaces the flags the app gives
# WebView2, so the app's own flags (WEBVIEW_BROWSER_ARGS in profile.rs, read
# from this checkout) are repeated next to the DevTools port.
$ProfileSource = Join-Path $PSScriptRoot '../app/src-tauri/src/profile.rs'
$AppWebViewArgs = [regex]::Match((Get-Content -Raw -LiteralPath $ProfileSource), 'WEBVIEW_BROWSER_ARGS: &str =\s*"([^"]+)"')
if (-not $AppWebViewArgs.Success) { throw "WEBVIEW_BROWSER_ARGS not found in $ProfileSource" }
$BaseWebViewArgs = if ($WebViewArgsOverride) { $WebViewArgsOverride } else { $AppWebViewArgs.Groups[1].Value }
$WebViewArgs = "$BaseWebViewArgs --remote-debugging-port=$CdpPort"
if ($WebViewArgsOverride -and ($BudgetIdleMB -gt 0 -or $BudgetWindowSeconds -gt 0)) {
    throw 'Budgets apply to the app as built: -WebViewArgsOverride cannot be combined with them.'
}

# Environment variables never passed to the measured app: provider keys and
# tokens of whoever runs this, and settings that would change what is measured.
$StrippedEnv = '(?i)(API_KEY|_TOKEN|_SECRET|PASSWORD|^SHODH_|^MODEL_PATH$|^WEBVIEW2_|^RUST_LOG$)'

function Get-EpochMs {
    [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
}

function Get-Median([double[]]$Values) {
    if (-not $Values -or $Values.Count -eq 0) { return $null }
    $sorted = @($Values | Sort-Object)
    $n = $sorted.Count
    if ($n % 2 -eq 1) { return [double]$sorted[($n - 1) / 2] }
    return ([double]$sorted[$n / 2 - 1] + [double]$sorted[$n / 2]) / 2
}

function Get-Group([string]$Name) {
    if ($Name -ieq $ExeName) { return 'core' }
    if ($Name -ieq 'msedgewebview2.exe') { return 'webview2' }
    if ($Name -match '^(?i)omp') { return 'agent-runtime' }
    return 'other'
}

# The launched process and every process it started (recursively), created
# after it (a recycled parent id never pulls in an unrelated process).
function Get-ProcessTree([int]$RootId, [datetime]$RootStart) {
    $all = Get-CimInstance -ClassName Win32_Process -Property ProcessId, ParentProcessId, Name, PrivatePageCount, WorkingSetSize, CreationDate
    $byParent = @{}
    $root = $null
    foreach ($p in $all) {
        if ([int]$p.ProcessId -eq $RootId) { $root = $p; continue }
        $parent = [int]$p.ParentProcessId
        if (-not $byParent.ContainsKey($parent)) { $byParent[$parent] = New-Object System.Collections.ArrayList }
        [void]$byParent[$parent].Add($p)
    }
    if ($null -eq $root) { return @() }
    $tree = New-Object System.Collections.ArrayList
    [void]$tree.Add($root)
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue([int]$RootId)
    while ($queue.Count -gt 0) {
        $id = $queue.Dequeue()
        if (-not $byParent.ContainsKey($id)) { continue }
        foreach ($child in $byParent[$id]) {
            if ($child.CreationDate -and $child.CreationDate -lt $RootStart.AddSeconds(-1)) { continue }
            [void]$tree.Add($child)
            $queue.Enqueue([int]$child.ProcessId)
        }
    }
    return $tree
}

function Get-Sample([int]$RootId, [datetime]$RootStart, [long]$LaunchMs) {
    $tree = @(Get-ProcessTree $RootId $RootStart)
    $groups = [ordered]@{ 'core' = 0.0; 'webview2' = 0.0; 'agent-runtime' = 0.0; 'other' = 0.0 }
    $counts = [ordered]@{ 'core' = 0; 'webview2' = 0; 'agent-runtime' = 0; 'other' = 0 }
    $others = New-Object System.Collections.ArrayList
    $workingSet = 0.0
    foreach ($p in $tree) {
        $group = Get-Group $p.Name
        $groups[$group] += [double]$p.PrivatePageCount / 1MB
        $counts[$group] += 1
        $workingSet += [double]$p.WorkingSetSize / 1MB
        if ($group -eq 'other') { [void]$others.Add($p.Name) }
    }
    $total = 0.0
    foreach ($v in $groups.Values) { $total += $v }
    $rounded = [ordered]@{}
    foreach ($k in $groups.Keys) { $rounded[$k] = [math]::Round($groups[$k], 1) }
    [pscustomobject][ordered]@{
        tSeconds       = [math]::Round(((Get-EpochMs) - $LaunchMs) / 1000.0, 1)
        totalMB        = [math]::Round($total, 1)
        workingSetMB   = [math]::Round($workingSet, 1)
        groupsMB       = $rounded
        processCounts  = $counts
        otherProcesses = @($others | Sort-Object -Unique)
        alive          = ($tree.Count -gt 0)
    }
}

# --- DevTools protocol (WebView2 remote debugging) ---------------------------

function Get-PageSocketUrl {
    try {
        $targets = Invoke-RestMethod -Uri "http://127.0.0.1:$CdpPort/json/list" -TimeoutSec 2 -UseBasicParsing
    } catch {
        return $null
    }
    $page = @($targets | Where-Object { $_.type -eq 'page' -and $_.url -notmatch '^(devtools|about:)' }) | Select-Object -First 1
    if ($null -eq $page) { return $null }
    return $page.webSocketDebuggerUrl
}

function Connect-Cdp([string]$Url) {
    $socket = New-Object System.Net.WebSockets.ClientWebSocket
    [void]$socket.ConnectAsync([Uri]$Url, [Threading.CancellationToken]::None).GetAwaiter().GetResult()
    return [pscustomobject]@{ Socket = $socket; NextId = 1 }
}

function Close-Cdp($Cdp) {
    if ($null -eq $Cdp) { return }
    try {
        [void]$Cdp.Socket.CloseAsync([System.Net.WebSockets.WebSocketCloseStatus]::NormalClosure, '', [Threading.CancellationToken]::None).GetAwaiter().GetResult()
    } catch {
        # The app may already be gone.
    }
    $Cdp.Socket.Dispose()
}

# Evaluate a JavaScript expression in the page and return its value.
function Invoke-PageScript($Cdp, [string]$Expression, [int]$TimeoutSeconds = 10) {
    $id = $Cdp.NextId
    $Cdp.NextId = $id + 1
    $request = @{
        id     = $id
        method = 'Runtime.evaluate'
        params = @{ expression = $Expression; awaitPromise = $true; returnByValue = $true }
    } | ConvertTo-Json -Depth 5 -Compress
    $bytes = [Text.Encoding]::UTF8.GetBytes($request)
    $segment = New-Object 'System.ArraySegment[byte]' -ArgumentList @(, $bytes)
    [void]$Cdp.Socket.SendAsync($segment, [System.Net.WebSockets.WebSocketMessageType]::Text, $true, [Threading.CancellationToken]::None).GetAwaiter().GetResult()

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $buffer = New-Object byte[] 65536
    while ((Get-Date) -lt $deadline) {
        $message = New-Object System.IO.MemoryStream
        do {
            $receiveSegment = New-Object 'System.ArraySegment[byte]' -ArgumentList @(, $buffer)
            $cts = New-Object Threading.CancellationTokenSource
            $cts.CancelAfter([math]::Max(100, [int]($deadline - (Get-Date)).TotalMilliseconds))
            $result = $Cdp.Socket.ReceiveAsync($receiveSegment, $cts.Token).GetAwaiter().GetResult()
            $message.Write($buffer, 0, $result.Count)
        } while (-not $result.EndOfMessage)
        $reply = [Text.Encoding]::UTF8.GetString($message.ToArray()) | ConvertFrom-Json
        if ($reply.PSObject.Properties['id'] -and $reply.id -eq $id) {
            if ($reply.PSObject.Properties['error']) { throw "DevTools error: $($reply.error.message)" }
            if ($reply.result.PSObject.Properties['exceptionDetails']) {
                throw "Page script failed: $($reply.result.exceptionDetails.text)"
            }
            if ($reply.result.result.PSObject.Properties['value']) { return $reply.result.result.value }
            return $null
        }
    }
    throw "DevTools did not answer within $TimeoutSeconds s"
}

